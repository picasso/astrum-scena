import { existsSync } from 'node:fs'
import path from 'node:path'
import { isDeepStrictEqual } from 'node:util'

import { z } from 'astro/zod'
import { parse, stringify } from 'yaml'

import {
	enabledModules,
	moduleCollections,
	MODULES,
	type ModulesSection,
} from '../modules/registry.ts'
import { COLLECTION_SOURCES } from './collection-sources.ts'
import { assertSchemaVersion, assertSupportedVersion } from './schema-version.ts'
import { siteSchema } from './site-schema.ts'
import { readYaml, validate } from './yaml-file.ts'

// the site writes site.yaml, its data and overrides; resolve merges it with the core defaults into
// site.lock.yaml, the strict effective config with the versions of the content collections, which the
// site commits and everything else reads (src/config/loader.ts). A new core default thus reaches a
// site only as a diff of its lock. This module is the only reader of site.yaml.

export const SITE_CONFIG_PATH = 'site.yaml'
export const SITE_LOCK_PATH = 'site.lock.yaml'

const LOCK_SCHEMA_VERSION = 1

export const UPGRADE_HINT = 'see UPGRADING.md'
export const RESOLVE_HINT = 'run astrum-scena config resolve'

// issues a check outside the schema finds in the config, named by the key path a site writes
export const siteConfigError = (issues: readonly { path: PropertyKey[]; message: string }[]) =>
	new Error(
		issues
			.map(
				(issue) =>
					`${SITE_CONFIG_PATH}: ${issue.path.map(String).join('.')}: ${issue.message}`,
			)
			.join('\n'),
	)

const LOCK_HEADER = `# generated by pnpm config:resolve from ${SITE_CONFIG_PATH} and the core defaults; do not edit`

// the files site.yaml replaced; one left behind means an unfinished migration, so resolve and the
// loader fail instead of silently ignoring it
export const RETIRED_CONFIG_FILES: Readonly<Record<string, string>> = {
	'src/config/site.yaml': 'moved to site.yaml at the site root',
	'src/config/seo.yaml': 'folded into site.yaml (seo)',
	'config/images.yaml': 'folded into site.yaml (images)',
}

export const assertNoRetiredFiles = (root: string): void => {
	for (const [file, fate] of Object.entries(RETIRED_CONFIG_FILES))
		if (existsSync(path.resolve(root, file)))
			throw new Error(`${file}: ${fate}; ${UPGRADE_HINT}`)
}

type Versions = readonly [number, ...number[]]

const CORE_COLLECTION_NAMES = Object.keys(COLLECTION_SOURCES)

// the shapes of each content collection the core reads, the last one current: the core's own and
// those of every module. Resolve keeps the version a lock already holds and writes the current one
// only for a collection the lock lacks, so a new shape reaches a site through the upgrade step that
// raises its version, never through resolve. Version 2 of albums and photos has a text per active
// locale instead of an `{en, ru}` pair
const CORE_COLLECTION_VERSIONS: Readonly<Record<string, Versions>> = { albums: [2], photos: [2] }

export const COLLECTION_VERSIONS: Readonly<Record<string, Versions>> = {
	...Object.fromEntries(
		CORE_COLLECTION_NAMES.map((name) => [name, CORE_COLLECTION_VERSIONS[name] ?? [1]]),
	),
	...Object.fromEntries(
		Object.entries(moduleCollections(MODULES)).map(([name, { versions }]) => [name, versions]),
	),
}

// a module's collections are in the lock only while the site enables the module
const moduleOwner = new Map(
	MODULES.flatMap((module) => Object.keys(module.collections).map((name) => [name, module.id])),
)

const lockCollectionNames = (site: { modules: ModulesSection }): string[] => [
	...CORE_COLLECTION_NAMES,
	...Object.keys(moduleCollections(enabledModules(site))),
]

const currentVersion = (name: string): number => COLLECTION_VERSIONS[name]!.at(-1)!

// strict like site.yaml, and with no defaults left to apply: the loader checks that parsing `site`
// adds nothing, so every branch of the effective config is written out
export const siteLockSchema = z
	.object({
		schemaVersion: z.literal(LOCK_SCHEMA_VERSION),
		collections: z
			.object(
				Object.fromEntries(
					Object.entries(COLLECTION_VERSIONS).map(([name, versions]) => {
						const version = z.literal([...versions])
						return [name, moduleOwner.has(name) ? version.optional() : version]
					}),
				) as Record<string, z.ZodLiteral<number> | z.ZodOptional<z.ZodLiteral<number>>>,
			)
			.strict(),
		site: siteSchema,
	})
	.strict()

export type SiteLock = z.infer<typeof siteLockSchema>

const isMapping = (value: unknown): value is Record<string, unknown> =>
	value !== null && typeof value === 'object' && !Array.isArray(value)

// the first place where the written lock differs from its parse: a default or transform that fired
// there means the branch was not written in its resolved form
const divergence = (parsed: unknown, written: unknown, at: string[]): string | undefined => {
	const where = at.join('.')
	if (isMapping(parsed) && isMapping(written)) {
		for (const [key, value] of Object.entries(parsed)) {
			if (!Object.hasOwn(written, key)) return `${where}.${key}: missing`
			const found = divergence(value, written[key], [...at, key])
			if (found) return found
		}
		return Object.keys(written).length === Object.keys(parsed).length
			? undefined
			: `${where}: not in its resolved form`
	}
	if (Array.isArray(parsed) && Array.isArray(written) && parsed.length === written.length) {
		for (const [index, value] of parsed.entries()) {
			const found = divergence(value, written[index], [...at, String(index)])
			if (found) return found
		}
		return undefined
	}
	return isDeepStrictEqual(parsed, written) ? undefined : `${where}: not in its resolved form`
}

const modulesOf = (site: unknown): { modules: ModulesSection } => ({
	modules: isMapping(site) && isMapping(site.modules) ? site.modules : {},
})

// the collections of the core and of the modules `site` enables, and no other
const assertCollectionVersions = (collections: unknown, site: unknown, filePath: string): void => {
	if (!isMapping(collections))
		throw new Error(`${filePath}: collections: missing; ${RESOLVE_HINT}`)
	const names = lockCollectionNames(modulesOf(site))
	for (const name of names) {
		if (!Object.hasOwn(collections, name))
			throw new Error(`${filePath}: collections.${name}: missing; ${RESOLVE_HINT}`)
		assertSupportedVersion(
			collections[name],
			`${filePath}: collections.${name}: version`,
			COLLECTION_VERSIONS[name]!,
			UPGRADE_HINT,
		)
	}
	for (const name of Object.keys(collections)) {
		const owner = moduleOwner.get(name)
		if (owner && !names.includes(name))
			throw new Error(
				`${filePath}: collections.${name}: module "${owner}" is not enabled; ${RESOLVE_HINT}`,
			)
	}
}

// the lock as the loader accepts it: its own version, the collection versions the core reads, the
// version of the site config it was resolved from, then the schema and the fixed point
export function parseSiteLock(raw: unknown, filePath: string): SiteLock {
	assertSchemaVersion(raw, filePath, siteLockSchema, UPGRADE_HINT)
	const { collections, site } = raw as Record<string, unknown>
	assertSchemaVersion(site, `${filePath}: site`, siteSchema.in, UPGRADE_HINT)
	assertCollectionVersions(collections, site, filePath)
	const lock = validate(siteLockSchema, raw, filePath)
	const found = divergence(lock.site, site, ['site'])
	if (found) throw new Error(`${filePath}: ${found}; ${RESOLVE_HINT}`)
	return lock
}

// the versions of the lock already at the root, the current ones for a collection it lacks; a
// collection the core no longer has, or of a module the site no longer enables, is dropped
const lockedCollections = (
	root: string,
	site: { modules: ModulesSection },
): Record<string, unknown> => {
	const existing = existsSync(path.resolve(root, SITE_LOCK_PATH))
		? readYaml(root, SITE_LOCK_PATH)
		: undefined
	const locked =
		isMapping(existing) && isMapping(existing.collections) ? existing.collections : {}
	return Object.fromEntries(
		lockCollectionNames(site).map((name) => [
			name,
			Object.hasOwn(locked, name) ? locked[name] : currentVersion(name),
		]),
	)
}

// the text of site.lock.yaml for the site at `root`: deterministic (keys in schema order), so a rerun
// on the same inputs is byte-identical and the drift gate can compare bytes
export function resolveSiteLock(root: string): string {
	assertNoRetiredFiles(root)
	const raw = readYaml(root, SITE_CONFIG_PATH)
	assertSchemaVersion(raw, SITE_CONFIG_PATH, siteSchema.in, UPGRADE_HINT)
	// parsing the effective config again puts a key a transform appended back in schema order
	const site = siteSchema.parse(validate(siteSchema, raw, SITE_CONFIG_PATH))
	// a version carried over from the lock fails here as it would in the loader
	const collections = lockedCollections(root, site)
	assertCollectionVersions(collections, site, SITE_LOCK_PATH)
	const text = `${LOCK_HEADER}\n${stringify(
		{ schemaVersion: LOCK_SCHEMA_VERSION, collections, site },
		{ aliasDuplicateObjects: false, indent: 4, lineWidth: 0 },
	)}`
	const written = (parse(text) as { site: unknown }).site
	const found = divergence(siteSchema.parse(written), written, ['site'])
	if (found) throw new Error(`the core resolved ${SITE_CONFIG_PATH} to no fixed point: ${found}`)
	return text
}
