import {
	cpSync,
	existsSync,
	mkdirSync,
	mkdtempSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { isDeepStrictEqual } from 'node:util'

import { afterAll, afterEach, beforeAll, describe, expect, it, vi } from 'vitest'
import { parse, stringify } from 'yaml'

import { COLLECTION_SOURCES } from './collection-sources.ts'
import { buildSiteConfig } from './fixtures/site-config.ts'
import { writeSiteConfig, writeSiteFiles } from './fixtures/site-files.ts'
import { loadSiteConfig, loadSiteSection, SITE_LOCK_ENV } from './loader.ts'
import {
	COLLECTION_VERSIONS,
	resolveSiteLock,
	RETIRED_CONFIG_FILES,
	SITE_CONFIG_PATH,
	SITE_LOCK_PATH,
} from './lock.ts'
import { siteRoot } from './site-root.ts'
import { siteSchema } from './site-schema.ts'

const roots: string[] = []

const makeRoot = (): string => {
	const root = mkdtempSync(path.join(tmpdir(), 'config-lock-'))
	roots.push(root)
	return root
}

type Lock = { schemaVersion: number; collections: Record<string, unknown>; site: unknown }
const resolved = (root: string): Lock => parse(resolveSiteLock(root)) as Lock
const resolveConfig = (config: object | string) => resolved(writeSiteConfig(makeRoot(), config))
const readSiteYaml = (root: string) =>
	parse(readFileSync(path.join(root, SITE_CONFIG_PATH), 'utf8')) as Record<string, unknown>

// the core's collections and the courses module's, which the demo and the fixture config enable
const CURRENT = Object.fromEntries(
	[...Object.keys(COLLECTION_SOURCES), 'courses'].map((name) => [
		name,
		COLLECTION_VERSIONS[name]!.at(-1),
	]),
)

beforeAll(() => {
	vi.stubEnv(SITE_LOCK_ENV, '')
})

afterAll(() => {
	vi.unstubAllEnvs()
})

afterEach(() => {
	for (const root of roots.splice(0)) rmSync(root, { force: true, recursive: true })
})

describe('resolveSiteLock', () => {
	it("gives the demo's committed lock byte for byte, its site the parsed site.yaml", () => {
		const text = resolveSiteLock(siteRoot)

		expect(readFileSync(path.join(siteRoot, SITE_LOCK_PATH), 'utf8')).toBe(text)
		expect(parse(text).site).toEqual(siteSchema.parse(readSiteYaml(siteRoot)))
	})

	it('starts with the generated header and holds its version, the collections and the site', () => {
		const text = resolveSiteLock(siteRoot)
		const lock = parse(text) as Lock

		expect(text.split('\n')[0]).toBe(
			'# generated by pnpm config:resolve from site.yaml and the core defaults; do not edit',
		)
		expect(Object.keys(lock)).toEqual(['schemaVersion', 'collections', 'site'])
		expect(lock.schemaVersion).toBe(1)
		expect(lock.collections).toEqual(CURRENT)
	})

	it('writes the keys in schema order whatever order site.yaml has', () => {
		const config = buildSiteConfig()
		const reversed = Object.fromEntries(Object.entries(config).reverse())
		const lock = resolveConfig(reversed)
		const site = lock.site as Record<string, Record<string, unknown>>

		expect(Object.keys(site)).toEqual(Object.keys(siteSchema.in.shape))
		expect(Object.keys(site.images!)[0]).toBe('publicPath')
		expect(resolveSiteLock(writeSiteConfig(makeRoot(), config))).toBe(
			resolveSiteLock(writeSiteConfig(makeRoot(), reversed)),
		)
	})

	it('is byte-identical on a rerun over its own lock', () => {
		const root = writeSiteFiles(makeRoot(), buildSiteConfig())
		const first = readFileSync(path.join(root, SITE_LOCK_PATH), 'utf8')

		expect(resolveSiteLock(root)).toBe(first)
	})

	it('keeps the collection versions of the existing lock and the current one for the rest', () => {
		const root = writeSiteFiles(makeRoot(), buildSiteConfig())
		const file = path.join(root, SITE_LOCK_PATH)
		const lock = parse(readFileSync(file, 'utf8')) as Lock
		const { photos: _photos, ...kept } = lock.collections
		void _photos
		writeFileSync(file, stringify({ ...lock, collections: { ...kept, retired: 3 } }))

		expect(resolved(root).collections).toEqual(CURRENT)
		expect(Object.keys(resolved(root).collections)).toEqual(Object.keys(CURRENT))
	})

	it('fails like the loader on a collection version of the lock the core does not read', () => {
		const root = writeSiteFiles(makeRoot(), buildSiteConfig())
		const file = path.join(root, SITE_LOCK_PATH)
		const lock = parse(readFileSync(file, 'utf8')) as Lock
		writeFileSync(
			file,
			stringify({ ...lock, collections: { ...lock.collections, photos: 99 } }),
		)
		const message = `${SITE_LOCK_PATH}: collections.photos: version 99 is not supported; supported: ${COLLECTION_VERSIONS.photos!.join(', ')}; see UPGRADING.md`

		expect(() => resolveSiteLock(root)).toThrow(message)
		expect(() => loadSiteConfig(root)).toThrow(message)
	})

	it('fails on a misspelt key in site.yaml with its path', () => {
		expect(() => resolveConfig({ ...buildSiteConfig(), theme: { defualt: 'light' } })).toThrow(
			`${SITE_CONFIG_PATH}: theme.defualt: unrecognized key`,
		)
	})

	it('fails on an unknown key at any depth of site.yaml with its full path', () => {
		const config = buildSiteConfig()
		const { recentWorks } = config.footer
		if (recentWorks === 'off') throw new Error('the fixture must hold a recentWorks object')

		expect(() =>
			resolveConfig({
				...config,
				images: { ...config.images, ladder: { ...config.images.ladder, widthz: [1] } },
			}),
		).toThrow(`${SITE_CONFIG_PATH}: images.ladder.widthz: unrecognized key`)
		expect(() => resolveConfig({ ...config, extra: 1 })).toThrow(
			`${SITE_CONFIG_PATH}: extra: unrecognized key`,
		)
		expect(() =>
			resolveConfig({
				...config,
				footer: { ...config.footer, recentWorks: { ...recentWorks, countz: 6 } },
			}),
		).toThrow(`${SITE_CONFIG_PATH}: footer.recentWorks.countz: unrecognized key`)
	})

	it('rejects the old shapes of site.yaml with the supported version and the migration', () => {
		for (const schemaVersion of [1, 2, 3])
			expect(() => resolveConfig({ ...buildSiteConfig(), schemaVersion })).toThrow(
				`${SITE_CONFIG_PATH}: schemaVersion ${schemaVersion} is not supported; supported: 4; see UPGRADING.md`,
			)
		expect(() => resolved(makeRoot())).toThrow(SITE_CONFIG_PATH)
	})

	// version 2 kept the course settings at the top level; in 3 they are `modules.courses`
	it('rejects the course sections of version 2 under version 3, naming each key', () => {
		const config = buildSiteConfig() as unknown as Record<string, Record<string, unknown>>
		const old = {
			...config,
			courses: { order: 'title' },
			moreDocs: { ...config.moreDocs, course: config.moreDocs!.page },
			surfaces: { ...config.surfaces, coursesIndex: { kind: 'list' } },
		}
		const message = (() => {
			try {
				resolveConfig(old)
			} catch (error) {
				return (error as Error).message
			}
		})()

		expect(message).toContain(`${SITE_CONFIG_PATH}: courses: unrecognized key`)
		expect(message).toContain(`${SITE_CONFIG_PATH}: moreDocs.course: unrecognized key`)
		expect(message).toContain(`${SITE_CONFIG_PATH}: surfaces.coursesIndex: unrecognized key`)
	})

	it('writes the collections of an enabled module and drops them once it is disabled', () => {
		const enabled = writeSiteFiles(makeRoot(), buildSiteConfig())
		const config = buildSiteConfig()
		const disabled = {
			...config,
			modules: {},
			menu: {
				...config.menu,
				items: config.menu.items.filter((item) => item.segment !== 'courses'),
			},
		}

		expect(parse(readFileSync(path.join(enabled, SITE_LOCK_PATH), 'utf8')).collections).toEqual(
			CURRENT,
		)
		writeSiteConfig(enabled, disabled)
		const { courses: _courses, ...core } = CURRENT
		void _courses
		expect(resolved(enabled).collections).toEqual(core)
	})

	it.each(Object.entries(RETIRED_CONFIG_FILES))(
		'fails while %s is left beside site.yaml',
		(file, fate) => {
			const root = writeSiteConfig(makeRoot(), buildSiteConfig())
			mkdirSync(path.dirname(path.join(root, file)), { recursive: true })
			writeFileSync(path.join(root, file), 'schemaVersion: 1\n')

			expect(() => resolveSiteLock(root)).toThrow(`${file}: ${fate}; see UPGRADING.md`)
		},
	)
})

// the site's own data, with every behaviour section left to the core
const dataOnly = (): Record<string, unknown> => {
	const config = buildSiteConfig()
	return {
		schemaVersion: config.schemaVersion,
		origin: config.origin,
		identity: config.identity,
		content: config.content,
		privacy: config.privacy,
		menu: { items: config.menu.items },
		// enabling a module is the site's choice, not a default
		modules: { courses: {} },
		social: config.social,
		seo: { description: config.seo.description },
		images: { rights: config.images.rights, watermark: config.images.watermark },
	}
}

const DATA_KEYS = new Set(Object.keys(dataOnly()))

describe('core defaults of site.yaml', () => {
	const load = (config: object) => loadSiteConfig(writeSiteFiles(makeRoot(), config))

	it('locks a site.yaml of data only with every behaviour section at its default', () => {
		const loaded = load(dataOnly())
		const behaviour = Object.keys(siteSchema.in.shape).filter((key) => !DATA_KEYS.has(key))

		expect(behaviour.length).toBeGreaterThan(0)
		for (const key of behaviour)
			expect(loaded).toHaveProperty(
				key,
				siteSchema.in.shape[key as keyof typeof siteSchema.in.shape].parse(undefined),
			)
		expect(loaded.menu.animate).toBe('word-slide-in')
		expect(loaded.images.ladder.widths).toEqual([200, 400, 800, 1200, 1600])
		expect(loaded.images.publicPath).toBe('/media')
	})

	it('merges a partial override into the section defaults', () => {
		const root = writeSiteFiles(makeRoot(), { ...dataOnly(), viewer: { counter: 'on' } })
		const defaults = siteSchema.in.shape.viewer.parse(undefined)

		expect(defaults.counter).toBe('off')
		expect(loadSiteConfig(root).viewer).toEqual({ ...defaults, counter: 'on' })
		expect(loadSiteSection(root, 'viewer')).toEqual({ ...defaults, counter: 'on' })
	})

	it('requires the site data, naming the missing field', () => {
		const { identity: _identity, ...withoutIdentity } = dataOnly()
		void _identity

		expect(() => resolveConfig(withoutIdentity)).toThrow(`${SITE_CONFIG_PATH}: identity: `)
	})

	it('keeps a site.yaml with every field written valid and equal to its locked config', () => {
		const full = buildSiteConfig()

		expect(load(full)).toEqual(full)
	})

	// each node of the demo's site.yaml (an object, a scalar or an array) is site data (the file
	// fails without it) or an override (the effective config changes without it); one equal to the
	// core's default is dead weight that would hide a later change of that default. Objects count
	// too: a whole `moreDocs.<kind>` block equal to its default fails without any one of its leaves
	it("writes no value of the demo's site.yaml that equals the core default", () => {
		const raw = readSiteYaml(siteRoot)
		const effective = siteSchema.parse(raw)
		const nodes = (value: unknown, at: string[] = []): string[][] =>
			value !== null && typeof value === 'object' && !Array.isArray(value)
				? [
						...(at.length > 0 ? [at] : []),
						...Object.entries(value).flatMap(([key, child]) =>
							nodes(child, [...at, key]),
						),
					]
				: [at]
		const without = (leaf: string[]) => {
			const copy = structuredClone(raw)
			let node = copy
			for (const key of leaf.slice(0, -1)) node = node[key] as Record<string, unknown>
			delete node[leaf.at(-1)!]
			return copy
		}

		const asDefault = nodes(raw).filter((leaf) => {
			const result = siteSchema.safeParse(without(leaf))
			return result.success && isDeepStrictEqual(result.data, effective)
		})
		expect(asDefault.map((leaf) => leaf.join('.'))).toEqual([])
	})
})

// a site of the previous release (a copy of the demo's site.yaml before the lock) and the step of
// UPGRADING.md: resolve the lock and commit it; the effective config is the one that release loaded
describe('upgrade to the config lock', () => {
	const previousRoot = path.join(import.meta.dirname, '__fixtures__', 'override-tree-site')

	const copy = (): string => {
		const root = makeRoot()
		cpSync(previousRoot, root, { recursive: true })
		return root
	}

	it('fails to load without the lock, naming the command that writes it', () => {
		expect(existsSync(path.join(previousRoot, SITE_LOCK_PATH))).toBe(false)
		expect(() => loadSiteConfig(previousRoot)).toThrow(
			`${SITE_LOCK_PATH}: missing; run astrum-scena config resolve`,
		)
	})

	it('loads, once resolved, the config the previous release parsed from site.yaml', () => {
		const root = copy()
		writeFileSync(path.join(root, SITE_LOCK_PATH), resolveSiteLock(root))
		const previous = siteSchema.parse(readSiteYaml(previousRoot))

		expect(loadSiteConfig(root)).toEqual(previous)
		expect(loadSiteSection(root, 'images')).toEqual(previous.images)
		expect(parse(readFileSync(path.join(root, SITE_LOCK_PATH), 'utf8')).collections).toEqual(
			CURRENT,
		)
	})
})

// images.rights.source and webStatement follow origin unless site.yaml writes them (6.4, part D)
describe('image rights derived from origin', () => {
	type Rights = Record<string, unknown>
	const ORIGIN = 'https://demo.example.com'
	const lockedRights = (lock: Lock) => (lock.site as { images: { rights: Rights } }).images.rights
	const withRights = (origin: string, change: (rights: Rights) => void = () => {}) => {
		const config = dataOnly() as { origin: string; images: { rights: Rights } }
		const { source: _source, webStatement: _webStatement, ...rights } = config.images.rights
		void _source
		void _webStatement
		change(rights)
		return { ...config, origin, images: { ...config.images, rights } }
	}

	it('writes both fields into the lock from origin when site.yaml leaves them out', () => {
		expect(lockedRights(resolveConfig(withRights(ORIGIN)))).toMatchObject({
			source: 'demo.example.com',
			webStatement: 'https://demo.example.com/rights/',
		})
	})

	it('follows a change of origin', () => {
		expect(lockedRights(resolveConfig(withRights('https://moved.example.org')))).toMatchObject({
			source: 'moved.example.org',
			webStatement: 'https://moved.example.org/rights/',
		})
	})

	it('keeps a written value over the derived one', () => {
		const kept = { source: 'old.example.net', webStatement: 'https://old.example.net/rights/' }
		const config = withRights(ORIGIN, (rights) => Object.assign(rights, kept))

		expect(lockedRights(resolveConfig(config))).toMatchObject(kept)
	})

	it('keeps a written source and derives webStatement', () => {
		const config = withRights(ORIGIN, (rights) => (rights.source = 'old.example.net'))

		expect(lockedRights(resolveConfig(config))).toMatchObject({
			source: 'old.example.net',
			webStatement: 'https://demo.example.com/rights/',
		})
	})

	it('keeps a written webStatement and derives source', () => {
		const webStatement = 'https://old.example.net/rights/'
		const config = withRights(ORIGIN, (rights) => (rights.webStatement = webStatement))

		expect(lockedRights(resolveConfig(config))).toMatchObject({
			source: 'demo.example.com',
			webStatement,
		})
	})

	it.each(['source', 'webStatement'])(
		'fails to load a lock without the derived %s, naming its path',
		(field) => {
			const root = writeSiteFiles(makeRoot(), withRights(ORIGIN))
			const file = path.join(root, SITE_LOCK_PATH)
			const lock = parse(readFileSync(file, 'utf8')) as Lock
			delete lockedRights(lock)[field]
			writeFileSync(file, stringify(lock))

			expect(() => loadSiteConfig(root)).toThrow(
				`${SITE_LOCK_PATH}: site.images.rights.${field}: missing; run astrum-scena config resolve`,
			)
		},
	)

	// the step of UPGRADING.md on a site of the previous release: drop both lines from site.yaml,
	// where they equal the derived values, and resolve; the lock, and so configDigest, stay the same
	it('leaves the lock byte for byte the same once the site drops the two lines', () => {
		const root = makeRoot()
		cpSync(path.join(import.meta.dirname, '__fixtures__', 'override-tree-site'), root, {
			recursive: true,
		})
		const before = resolveSiteLock(root)
		const site = readSiteYaml(root) as { images: { rights: Rights } }
		expect(site.images.rights).toHaveProperty('source')
		expect(site.images.rights).toHaveProperty('webStatement')
		delete site.images.rights.source
		delete site.images.rights.webStatement
		writeSiteConfig(root, site)

		expect(resolveSiteLock(root)).toBe(before)
	})
})
